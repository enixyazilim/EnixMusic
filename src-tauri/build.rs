use std::fs;
use std::path::Path;

fn main() {
    // 1. Rust-native Injected Scripts Bundler (Eliminates NodeJS/npm build step)
    let injected_dir = Path::new("../injected");
    if injected_dir.exists() {
        println!("cargo:rerun-if-changed=../injected/styles.css");
        println!("cargo:rerun-if-changed=../injected/adblocker.js");
        println!("cargo:rerun-if-changed=../injected/av_switcher.js");
        println!("cargo:rerun-if-changed=../injected/audio_effects.js");
        println!("cargo:rerun-if-changed=../injected/settings.js");
        println!("cargo:rerun-if-changed=../injected/player_bridge.js");

        let styles = fs::read_to_string(injected_dir.join("styles.css")).unwrap_or_default();
        let adblocker = fs::read_to_string(injected_dir.join("adblocker.js")).unwrap_or_default();
        let av_switcher = fs::read_to_string(injected_dir.join("av_switcher.js")).unwrap_or_default();
        let audio_effects = fs::read_to_string(injected_dir.join("audio_effects.js")).unwrap_or_default();
        let settings = fs::read_to_string(injected_dir.join("settings.js")).unwrap_or_default();
        let player_bridge = fs::read_to_string(injected_dir.join("player_bridge.js")).unwrap_or_default();

        let escaped_css = styles
            .replace('\\', "\\\\")
            .replace('`', "\\`")
            .replace('$', "\\$");

        let style_injection = format!(
            r#"(function() {{
  if (location.hostname !== 'music.youtube.com') return;
  const css = `{}`;
  function addStyles() {{
    if (document.getElementById('enix-custom-ui-styles')) return;
    const s = document.createElement('style');
    s.id = 'enix-custom-ui-styles';
    s.textContent = css;
    (document.head || document.documentElement).appendChild(s);
  }}
  addStyles();
  if (document.readyState === 'loading') {{
    document.addEventListener('DOMContentLoaded', addStyles);
  }}
}})();"#,
            escaped_css
        );

        let bundle = format!(
            r#"// Auto-generated by Rust build.rs - DO NOT EDIT
(function() {{
  if (location.hostname !== 'music.youtube.com') return;

  // 1. Setup Trusted Types default bypass policy for Google/YouTube
  if (window.trustedTypes && window.trustedTypes.createPolicy) {{
    try {{
      window.trustedTypes.createPolicy('default', {{
        createHTML: (s) => s,
        createScript: (s) => s,
        createScriptURL: (s) => s,
      }});
    }} catch (_) {{}}
  }}

  // 2. Block unwanted beforeunload popups
  if (!window.__enix_beforeunload_handled) {{
    window.__enix_beforeunload_handled = true;
    const _ael = EventTarget.prototype.addEventListener;
    EventTarget.prototype.addEventListener = function(type, listener, options) {{
      if (type === 'beforeunload') return;
      return _ael.call(this, type, listener, options);
    }};
    Object.defineProperty(window, 'onbeforeunload', {{
      get() {{ return null; }},
      set(_) {{}},
      configurable: true
    }});
  }}

  // 3. Global error logger to track any issues
  window.addEventListener('error', (err) => {{
    console.debug('[Enix Runtime Log]:', err.message);
  }});

  {}

  {}

  {}

  {}

  {}

  {}
}})();
"#,
            style_injection, adblocker, av_switcher, audio_effects, settings, player_bridge
        );

        let _ = fs::write(injected_dir.join("bundle.js"), bundle);
    }

    // 2. Tauri build
    tauri_build::build()
}
